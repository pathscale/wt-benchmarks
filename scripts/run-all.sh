#!/bin/sh
# Every axis, one command, one file.
#
# The point is that a release run is not a judgement call about which
# benchmarks to run and at what size. It is this script. A number that is not
# in here did not get measured, and a number that is in here was measured the
# same way as every other.
#
# Usage:
#   scripts/run-all.sh [output.md]
#
# Environment:
#   WT_ROUNDS_ALL  repetitions for every suite (default 9). Three is not
#                  enough: it produced two reversals in this study.
#
# POSIX sh: no arrays, no [[ ]], no pipefail.
set -eu

OUT="${1:-benchmark.md}"
ROUNDS="${WT_ROUNDS_ALL:-9}"
ROOT=$(cd "$(dirname "$0")/.." && pwd)
BIN="$ROOT/target/release"
RAW="$ROOT/target/benchmark-rows"
mkdir -p "$RAW"

FEATURES="worktable-adapter persisted-grid versioned-row-publication"

echo "building" >&2
cargo build --release --features "$FEATURES" \
    --bin mixed-runtime-worktable \
    --bin backend-grid-worktable \
    --bin page-size-worktable \
    --bin persisted-grid-worktable \
    --bin ycsb-worktable \
    --bin summarize-grid >&2

# One file per suite, kept rather than piped, so a summary can be regenerated
# without paying for the run again and so a suspicious table can be traced to
# the rows that produced it.
echo "flavors and split, 6 readers 2 writers" >&2
WT_JSON=1 WT_ROUNDS="$ROUNDS" WT_OPS=150000 "$BIN/mixed-runtime-worktable" 2>/dev/null \
    | grep '^{' > "$RAW/flavors.jsonl"

echo "concurrency sweep" >&2
: > "$RAW/concurrency.jsonl"
for level in "6 2" "12 4" "24 8" "48 16"; do
    set -- $level
    WT_JSON=1 WT_ROUNDS="$ROUNDS" WT_READERS="$1" WT_WRITERS="$2" WT_OPS=60000 \
        "$BIN/mixed-runtime-worktable" 2>/dev/null | grep '^{' >> "$RAW/concurrency.jsonl"
done

echo "index backend by concurrency" >&2
WT_JSON=1 WT_ROUNDS="$ROUNDS" WT_OPS=12000 "$BIN/backend-grid-worktable" 2>/dev/null \
    | grep '^{' > "$RAW/backend.jsonl"

echo "page size, in memory" >&2
WT_JSON=1 WT_ROUNDS_N="$ROUNDS" WT_OPS=20000 "$BIN/page-size-worktable" 2>/dev/null \
    | grep '^{' > "$RAW/page-size.jsonl"

echo "page size, persisted" >&2
WT_JSON=1 WT_ROUNDS_N="$ROUNDS" WT_OPS=4000 "$BIN/persisted-grid-worktable" 2>/dev/null \
    | grep '^{' > "$RAW/persisted.jsonl"

echo "ycsb C, 16 threads" >&2
"$BIN/ycsb-worktable" --workload C --threads 16 --repetitions "$ROUNDS" \
    --operations 1500000 2>/dev/null > "$RAW/ycsb.jsonl"

{
    echo "# WorkTable benchmark run"
    echo
    echo "Generated by \`scripts/run-all.sh\`, $ROUNDS repetitions per cell."
    echo "Raw rows are in \`target/benchmark-rows/\`; every table below is"
    echo "\`summarize-grid\` over one of those files and nothing was typed by hand."
    echo
    echo "A cell is compared only against the cell differing in one thing, the"
    echo "runtime. Where the ranges overlap no percentage is printed: the table"
    echo "says \`within noise\` and gives the spread, because a percentage a"
    echo "second run would reverse is worse than none."
    echo
    for suite in flavors concurrency backend page-size persisted ycsb; do
        echo "## $suite"
        echo
        "$BIN/summarize-grid" < "$RAW/$suite.jsonl" 2>/dev/null || echo "(no rows)"
        echo
    done
} > "$OUT"

echo "wrote $OUT" >&2
